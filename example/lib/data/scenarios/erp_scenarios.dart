  static ExampleScenario _scenario(ErpDialogSpec spec, int index) {
    const animations = <DialogAnimation>[
      DialogAnimation.centerScale,
      DialogAnimation.centerFade,
      DialogAnimation.endToStart,
      DialogAnimation.startToEnd,
      DialogAnimation.bottomToTop,
      DialogAnimation.topToBottom,
      DialogAnimation.expandVertical,
      DialogAnimation.expandHorizontal,
      DialogAnimation.expandCenter,
      DialogAnimation.slideScaleStart,
      DialogAnimation.slideScaleEnd,
      DialogAnimation.bounceIn,
      DialogAnimation.elasticIn,
      DialogAnimation.flipHorizontal,
      DialogAnimation.rotateScale,
      DialogAnimation.slideRotateBottom,
    ];
    final controlled = spec.pattern == ErpDialogPattern.postingConfirmation ||
        spec.pattern == ErpDialogPattern.closeChecklist ||
        spec.pattern == ErpDialogPattern.riskDecision;
    final wide = spec.pattern == ErpDialogPattern.splitComparison ||
        spec.pattern == ErpDialogPattern.controlMatrix ||
        spec.pattern == ErpDialogPattern.allocationWorkbench ||
        spec.pattern == ErpDialogPattern.documentPreview;

    return ExampleScenario(
      title: spec.title,
      description: spec.subtitle,
      animation: animations[index % animations.length],
      category: 'ERP',
      module: spec.module,
      reference: spec.reference,
      statusLabel: spec.status,
      statusColor: spec.statusColor,
      icon: spec.icon,
      accentColor: spec.accentColor,
      builder: (context) => ErpPatternDialog(spec: spec),
      constraints: wide ? const BoxConstraints(maxWidth: 800) : null,
      barrierDismissible: controlled ? false : null,
      barrierBlur: controlled ? 9 : 6,
      barrierColor: const Color(0x8F000000),
      tags: <String>[spec.pattern.label, ...spec.tags],
      designPattern: '${spec.pattern.label} · Variant ${index + 1}',
      designFamily: spec.pattern.label,
      isRecommended: index % 8 == 0 || controlled,
    );
  }
